/// An icon at the default size; colour it with `.text_color(..)`.
pub fn icon(icon: Icon) -> Svg {
    icon_sized(icon, size::ICON)
}

pub fn icon_sized(icon: Icon, size: Pixels) -> Svg {
    svg().path(icon.path()).size(size).flex_none()
}
